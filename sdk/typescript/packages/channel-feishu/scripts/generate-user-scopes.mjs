import { spawnSync } from 'node:child_process'
import { copyFile, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const officialCli = path.join(packageRoot, 'official-cli')
const lock = JSON.parse(await readFile(path.join(officialCli, 'lark-cli.lock.json'), 'utf8'))
const shortcuts = JSON.parse(await readFile(path.join(officialCli, 'lark-cli-shortcuts.json'), 'utf8'))
if (shortcuts.version !== lock.version) throw new Error('The shortcut catalog version does not match the lock.')
const runnerDomains = new Set(Object.keys(shortcuts.commands).map((command) => command.split(' ')[0]))

const moduleDir = await mkdtemp(path.join(tmpdir(), 'lark-cli-user-scopes-'))
try {
  await copyFile(path.join(officialCli, 'user-scopes', 'main.go'), path.join(moduleDir, 'main.go'))
  go(moduleDir, ['mod', 'init', 'lark-cli-user-scopes'])
  go(moduleDir, ['get', `github.com/larksuite/cli@v${lock.version}`])
  const declared = JSON.parse(go(moduleDir, ['run', '.']))
  const domains = Object.keys(declared)
    .filter((domain) => runnerDomains.has(domain))
    .sort()
    .map((domain) => ({ domain, scopes: [...declared[domain]].sort() }))
  const lines = [
    '// Generated by scripts/generate-user-scopes.mjs from the pinned lark-cli release. Do not edit.',
    `export const USER_SCOPE_CATALOG_VERSION = ${JSON.stringify(lock.version)};`,
    '',
    'export const USER_SCOPE_CATALOG: ReadonlyArray<{ domain: string; scopes: readonly string[] }> = [',
    ...domains.map(({ domain, scopes }) => `  { domain: ${JSON.stringify(domain)}, scopes: [${scopes.map((scope) => JSON.stringify(scope)).join(', ')}] },`),
    '];',
    ''
  ]
  await writeFile(path.join(packageRoot, 'src', 'user-scope-catalog.ts'), lines.join('\n'))
} finally {
  await rm(moduleDir, { recursive: true, force: true })
}

function go(cwd, args) {
  const result = spawnSync('go', args, { cwd, encoding: 'utf8' })
  if (result.status !== 0) throw new Error(`go ${args.join(' ')} failed: ${result.stderr}`)
  return result.stdout
}
