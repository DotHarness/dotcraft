<script setup lang="ts">
import { useData } from 'vitepress'
import { useEditUrl } from './docPage'

const { theme } = useData()
const editUrl = useEditUrl()

function backToTop(): void {
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches
  window.scrollTo({ top: 0, behavior: reduce ? 'auto' : 'smooth' })
}
</script>

<template>
  <div class="dc-outline-actions">
    <a v-if="editUrl" class="dc-outline-action" :href="editUrl" target="_blank" rel="noopener">
      <svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M12 3H5a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7" /><path d="M18.375 2.625a1 1 0 0 1 3 3l-9.013 9.014a2 2 0 0 1-.853.505l-2.873.84a.5.5 0 0 1-.62-.62l.84-2.873a2 2 0 0 1 .506-.852z" /></svg>
      {{ theme.editLink?.text }}
    </a>
    <button type="button" class="dc-outline-action" @click="backToTop">
      <svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="m5 12 7-7 7 7" /><path d="M12 19V5" /></svg>
      {{ theme.returnToTopLabel }}
    </button>
  </div>
</template>
