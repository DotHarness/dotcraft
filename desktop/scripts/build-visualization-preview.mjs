import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const destination = resolve(root, '../src/DotCraft.Core/Skills/BuiltIn/visualize/assets/preview.html')
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/renderer/components/conversation/visualizationPreview.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  plugins: [{
    name: 'raw-assets',
    setup(build) {
      build.onResolve({ filter: /\?raw$/ }, args => ({ path: resolve(args.resolveDir, args.path.slice(0, -4)), namespace: 'raw' }))
      build.onLoad({ filter: /.*/, namespace: 'raw' }, async args => ({ contents: await readFile(args.path, 'utf8'), loader: 'text' }))
    }
  }]
})
const { createPreviewTemplate } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`)
const template = ('<!-- Generated by desktop/scripts/build-visualization-preview.mjs. -->\n' + createPreviewTemplate()).replaceAll('\r\n', '\n')
if (Buffer.byteLength(template) >= 1024 * 1024) throw new Error('Preview template exceeds the skill asset limit of 1 MiB')
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== template) throw new Error('Visualization preview is stale. Run npm run generate:visualization-preview')
  process.stdout.write('Visualization preview is up to date.\n')
} else {
  await writeFile(destination, template)
  process.stdout.write(`Generated ${pathToFileURL(destination).href} (${Buffer.byteLength(template)} bytes)\n`)
}
