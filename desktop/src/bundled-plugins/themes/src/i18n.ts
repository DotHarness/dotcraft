function resolveLocale(locale: string): ThemeLocale {
  if (THEME_LOCALES.includes(locale as ThemeLocale)) return locale as ThemeLocale
  const base = locale.split('-')[0]
  return THEME_LOCALES.find((candidate) => candidate.split('-')[0] === base) ?? 'en'
}

export function stringsFor(locale: string): ThemeStrings {
  return CATALOG[resolveLocale(locale)]
}

export function themeDisplayName(theme: Pick<Theme, 'id' | 'name' | 'builtin'>, locale: string): string {
  return theme.builtin ? BUILTIN_THEME_NAMES[resolveLocale(locale)][theme.id] ?? theme.name : theme.name
}

export function translationsOf(key: keyof ThemeStrings): Record<string, string> {
  return Object.fromEntries(THEME_LOCALES.map((locale) => [locale, CATALOG[locale][key]]))
}
